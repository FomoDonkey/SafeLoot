-- Pure logic specs (no game behaviour involved).
local SL = NS
local P, R, J, M, N = SL.Proficiency, SL.Rules, SL.Judge, SL.Memory, SL.Names

test("proficiency: mage can never wear mail", function()
  eq(P.CanUse("MAGE", { classID = 4, subClassID = 3, equipLoc = "INVTYPE_CHEST" }), "no")
end)
test("proficiency: warrior wears plate", function()
  eq(P.CanUse("WARRIOR", { classID = 4, subClassID = 4, equipLoc = "INVTYPE_CHEST" }), "yes")
end)
test("proficiency: everyone wears cloaks (cloth subclass)", function()
  eq(P.CanUse("WARRIOR", { classID = 4, subClassID = 1, equipLoc = "INVTYPE_CLOAK" }), "yes")
end)
test("proficiency: rogue never uses a staff", function()
  eq(P.CanUse("ROGUE", { classID = 2, subClassID = 10, equipLoc = "INVTYPE_2HWEAPON" }), "no")
end)
test("proficiency: doubtful cases stay unknown (hunter + mace)", function()
  eq(P.CanUse("HUNTER", { classID = 2, subClassID = 4, equipLoc = "INVTYPE_WEAPON" }), "unknown")
end)
test("proficiency: shields only for warrior/paladin/shaman", function()
  eq(P.CanUse("PRIEST", { classID = 4, subClassID = 6, equipLoc = "INVTYPE_SHIELD" }), "no")
  eq(P.CanUse("SHAMAN", { classID = 4, subClassID = 6, equipLoc = "INVTYPE_SHIELD" }), "yes")
end)
test("proficiency: recipes and materials are never judged", function()
  eq(P.CanUse("MAGE", { classID = 9, subClassID = 0 }), "unknown")
end)
test("proficiency: exceptions silence a false positive", function()
  eq(P.CanUse("MAGE", { classID = 4, subClassID = 3 }, { ["MAGE:4:3"] = true }), "unknown")
end)

test("rules: Spanish/English listing text", function()
  local c = R.Parse("UBRS HR Mano de Dal'Rend, MS>OS", "Krag Hierro")
  ok(c, "parsed")
  eq(c.needRule, "msos")
  eq(#c.reserves, 1)
  eq(c.reserves[1].item, "Mano de Dal'Rend")
  eq(c.reserves[1].kind, "hard")
  eq(c.reserves[1].owner, "Krag Hierro")
end)
test("rules: item links are used as reserve names", function()
  local c = R.Parse("SR |cffa335ee|Hitem:12345::::::::60:::::|h[Hand of Dal'Rend]|h|r pls", "Krag")
  eq(c.reserves[1].item, "Hand of Dal'Rend")
  eq(c.reserves[1].kind, "soft")
end)
test("rules: master loot and greed in several languages", function()
  eq(R.Parse("ML on last boss").method, R.MASTER)
  eq(R.Parse("botín maestro al final").method, R.MASTER)
  eq(R.Parse("Plündermeister ab Boss 3").method, R.MASTER)
  eq(R.Parse("maître du butin").method, R.MASTER)
  eq(R.Parse("todo codicia por favor").needRule, "greed")
  eq(R.Parse("alles Gier bitte").needRule, "greed")
end)
test("rules: no false rules in normal chat", function()
  eq(R.Parse("hola a todos, vamos?"), nil)
  eq(R.Parse("señor, gracias"), nil)
  eq(R.Parse("thanks for the group"), nil)
end)
test("rules: agreement detection", function()
  for _, yes in ipairs({ "ok", "OK!", "Sí", "si", "+1", "vale", "yes", "oui", "ja", "sim", "de acuerdo", "¡ok!" }) do
    ok(R.IsAgreement(yes), "should agree: " .. yes)
  end
  for _, no in ipairs({ "no", "ok pero yo quiero la maza", "what?", "" }) do
    ok(not R.IsAgreement(no), "should not agree: " .. no)
  end
end)
test("rules: diff severities", function()
  local ref = { method = 3, leader = "Krag Hierro" }
  local changes = R.Diff(ref, { method = 2, masterLooter = "Krag Hierro", leader = "Krag Hierro" })
  eq(R.MaxSeverity(changes), R.SEVERITY_ALERT)
  eq(#R.Diff(ref, { method = 3, leader = "Krag Hierro" }), 0)
  eq(R.MaxSeverity(R.Diff({ method = 2, masterLooter = "Krag Hierro" }, { method = 3 })), R.SEVERITY_INFO)
  eq(R.MaxSeverity(R.Diff({ method = 2, masterLooter = "Krag Hierro" }, { method = 2, masterLooter = "Zarn Brasa" })), R.SEVERITY_ALERT)
  eq(R.MaxSeverity(R.Diff({ method = 3, threshold = 2 }, { method = 3, threshold = 4 })), R.SEVERITY_WARN)
end)
test("rules: chat line fits in 255 bytes", function()
  local c = R.New("proposed")
  c.method, c.needRule, c.boe = 3, "msos", "greed"
  for i = 1, 12 do
    c.reserves[i] = { item = "Very Long Legendary Item Name Number " .. i, owner = "Somebody Longname", kind = "hard" }
  end
  local line = R.ChatLine(c, SL.L)
  ok(#line <= 255, "length " .. #line)
  ok(contains(line, SL.L.CHAT_PREFIX), "prefix")
end)

test("judge: mage Need on mail is impossible", function()
  local v = J.Evaluate({ playerName = "Zarn Brasa", playerClass = "MAGE", state = J.NEED_MAIN },
    { name = "Coraza", classID = 4, subClassID = 3, equipLoc = "INVTYPE_CHEST" })
  eq(v.level, J.IMPOSSIBLE)
  eq(v.reason, "class_armor")
end)
test("judge: transmog and greed rolls are never faults", function()
  local item = { name = "Coraza", classID = 4, subClassID = 3, equipLoc = "INVTYPE_CHEST" }
  eq(J.Evaluate({ playerClass = "MAGE", state = J.TRANSMOG }, item), nil)
  eq(J.Evaluate({ playerClass = "MAGE", state = J.GREED }, item), nil)
end)
test("judge: Need on an item reserved for someone else is doubtful", function()
  local contract = R.New("proposed")
  R.Apply(contract, { reserves = { { item = "Anillo del Alba", owner = "Krag Hierro", kind = "hard" } } })
  local v = J.Evaluate({ playerName = "Zarn-Brasa", playerClass = "MAGE", state = J.NEED_MAIN },
    { name = "Anillo del Alba", classID = 4, subClassID = 0, equipLoc = "INVTYPE_FINGER" }, contract)
  eq(v.level, J.DOUBTFUL)
  eq(v.reason, "reserved_hard")
  -- the owner may Need on their own reserve
  eq(J.Evaluate({ playerName = "Krag Hierro", playerClass = "WARRIOR", state = J.NEED_MAIN },
    { name = "Anillo del Alba", classID = 4, subClassID = 0, equipLoc = "INVTYPE_FINGER" }, contract), nil)
end)
test("judge: 'all Greed' contract makes any Need doubtful", function()
  local contract = R.New("proposed")
  contract.needRule = "greed"
  local v = J.Evaluate({ playerClass = "WARRIOR", state = J.NEED_MAIN }, { name = "X", classID = 4, subClassID = 4 }, contract)
  eq(v.reason, "contract_greed")
end)

test("names: Forever name forms", function()
  eq(N.Short("El-Peregrino"), "El Peregrino")
  eq(N.Short("El Peregrino-Realm"), "El Peregrino")
  eq(N.Short("El Peregrino"), "El Peregrino")
  eq(N.Short("El"), "El")
  ok(N.Same("Krag-Hierro", "Krag Hierro"), "same")
  eq(N.Short(nil), nil)
end)

test("memory: add, summary tone and cap", function()
  local players = {}
  M.Add(players, "Zarn-Brasa", { kind = "need_impossible", t = SIM.now, class = "MAGE" })
  local rec = M.Get(players, "Zarn Brasa")
  ok(rec, "stored under the short name")
  eq(M.Summary(rec, SIM.now, 90).tone, "bad")
  M.Add(players, "Zarn Brasa", { kind = "tag_trusted", t = SIM.now })
  eq(M.Summary(rec, SIM.now, 90).tone, "mixed")
  for i = 1, 30 do
    M.Add(players, "Zarn Brasa", { kind = "note", t = SIM.now, note = "n" .. i })
  end
  eq(#rec.events, M.MAX_EVENTS)
  M.Add(players, "Zarn Brasa", { kind = "grouped", t = SIM.now })
  eq(#rec.events, M.MAX_EVENTS, "grouped never piles up")
end)
test("memory: expiry and pruning", function()
  local players = {}
  M.Add(players, "Old One", { kind = "tag_ninja", t = SIM.now - 100 * 86400 })
  M.Add(players, "New One", { kind = "tag_ninja", t = SIM.now })
  M.Prune(players, SIM.now, 90, 2000)
  eq(players["Old One"], nil)
  ok(players["New One"], "kept")
end)
